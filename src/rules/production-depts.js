const PRODUCTION_KEYWORDS = ['cắt', 'cut', 'chuyền may', 'may', 'sew', 'thêu', 'emb', 'in màu', 'in -', 'print',
  'hoàn thiện', 'finish', 'ủi', 'ironing', 'đóng gói', 'pack', 'đóng thùng', 'crating', 'đóng nút', 'button',
  'tất', 'sock', 'tinh anh', 'elite', 'kiểm hàng may', 'checking in line', 'sewing check'];

export function isProductionDeptName(name = '', engName = '') {
  const trimmed = (name || '').trim();
  if (PRODUCTION_DEPT_NAMES.has(trimmed)) return true;
  const s = `${trimmed} ${engName || ''}`.toLowerCase();
  if (SERVICE_KEYWORDS.some((k) => s.includes(k))) return false;
  if (EXCLUDE_KEYWORDS.some((k) => s.includes(k))) return false;
  return PRODUCTION_KEYWORDS.some((k) => s.includes(k));
}
